export const ui: Record<Locale, Record<UiKey, string>> = { en, de } as Record<Locale, Record<UiKey, string>>;
export const LOCALE_KEY = 'purrtion.locale';
let current: Locale = 'en';
/** Saved preference first, then a browser language starting with "de", else English. */
export function detectLocale(saved: string | null | undefined, language: string | null | undefined): Locale {
  if (saved === 'en' || saved === 'de') return saved;
  return (language ?? '').toLowerCase().startsWith('de') ? 'de' : 'en';
}
export function initLocale(): Locale {
  let saved: string | null = null;
  try { saved = localStorage.getItem(LOCALE_KEY); } catch { saved = null; }
  current = detectLocale(saved, typeof navigator === 'undefined' ? null : navigator.language);
  return current;
}
export function setLocale(locale: Locale): void {
  current = locale;
  try { localStorage.setItem(LOCALE_KEY, locale); } catch { /* the choice then lasts for this page only */ }
}
export function getLocale(): Locale { return current; }
export function translate(locale: Locale, key: UiKey, vars: Record<string, string> = {}): string {
  const text = ui[locale][key] ?? ui.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}
export function t(key: UiKey, vars: Record<string, string> = {}): string { return translate(current, key, vars); }
/** Engine text for a code. Unknown codes (from a newer engine) fall back to English, then to the code itself. */
export function msg(code: MessageKey | `${string}.${string}`): string {
  const table = messages[current] as Record<string, string>, english = messages.en as Record<string, string>;
  return table[code] ?? english[code] ?? code;
}
export function num(value: number, digits = 1, minimumDigits = 0): string {
  return new Intl.NumberFormat(current, { maximumFractionDigits: digits, minimumFractionDigits: minimumDigits }).format(value);
}
/** A calendar date (YYYY-MM-DD) in the active locale; parsed and shown in UTC so the day never shifts. */
export function dateText(iso: string): string {
  return new Intl.DateTimeFormat(current, { dateStyle: 'medium', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`));
}
export function shortDate(iso: string): string {
  return new Intl.DateTimeFormat(current, { day: 'numeric', month: 'short', timeZone: 'UTC' }).format(new Date(`${iso}T00:00:00Z`));
}
